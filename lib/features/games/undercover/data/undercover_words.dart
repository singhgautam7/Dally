/// The bank, built once. `civilian` is the majority word and `undercover` the
/// related-but-different one — but **which of the two is the majority word is
/// drawn per game**, so a pair does not always play the same way round.
final List<UndercoverWordPair> kUndercoverPairs = [
  for (final row in _raw)
    UndercoverWordPair(
      id: '${row[0]}|${row[1]}'.toLowerCase(),
      civilian: row[0],
      undercover: row[1],
      difficulty: switch (row[2]) {
        'e' => WordDifficulty.easy,
        'h' => WordDifficulty.hard,
        _ => WordDifficulty.normal,
      },
    ),
];
