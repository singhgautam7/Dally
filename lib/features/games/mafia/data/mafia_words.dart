/// The built, validated dataset. Ids are `word_hint`, lowercased and slugged.
final List<MafiaWordPair> kMafiaWordPairs = _raw
    .map((r) => MafiaWordPair(
          id: '${_slug(r[0])}_${_slug(r[1])}',
          word: r[0],
          hint: r[1],
          difficulty: switch (r[2]) {
            'e' => MafiaDifficulty.easy,
            'h' => MafiaDifficulty.hard,
            _ => MafiaDifficulty.normal,
          },
        ))
    .toList(growable: false);

String _slug(String s) => s.toLowerCase().replaceAll(RegExp(r'[^a-z0-9]+'), '_');
